#!/usr/bin/env node
/**
 * gen-starfield.mjs — 添付1枚目（濃紺のクリスタル質感＋星空）を再現。
 *  1) assets/starfield.svg    … 背景テクスチャ（グラデ＋クリスタル面＋グロー・静止）
 *  2) js/starfield.js         … 小さな星をSMILで非常にゆっくり瞬かせるインラインSVGを
 *                                濃色セクションに重ねて注入する（背景画像はアニメしないため）
 * 決定論的（mulberry32 PRNG）。
 */
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const W = 1600, H = 1100;

function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rr = (rnd, a, b) => a + (b - a) * rnd();
const f2 = (n) => Math.round(n * 10) / 10;

// ============ 1) 背景テクスチャ（クリスタル面＋グロー・星なし） ============
{
  const rnd = mulberry32(20260706);
  const COLS = 11, ROWS = 8;
  const cw = W / COLS, ch = H / ROWS;
  const pt = [];
  for (let y = 0; y <= ROWS; y++) {
    pt[y] = [];
    for (let x = 0; x <= COLS; x++) {
      const jx = (x === 0 || x === COLS) ? 0 : rr(rnd, -cw * 0.38, cw * 0.38);
      const jy = (y === 0 || y === ROWS) ? 0 : rr(rnd, -ch * 0.38, ch * 0.38);
      pt[y][x] = [f2(x * cw + jx), f2(y * ch + jy)];
    }
  }
  const facets = [];
  for (let y = 0; y < ROWS; y++) {
    for (let x = 0; x < COLS; x++) {
      const a = pt[y][x], b = pt[y][x + 1], c = pt[y + 1][x + 1], d = pt[y + 1][x];
      const base = 0.5 - (y / ROWS) * 0.5;
      for (const tri of [[a, b, c], [a, c, d]]) {
        const l = Math.max(0, Math.min(1, base + rr(rnd, -0.14, 0.14)));
        const r = Math.round(23 + l * 35), g = Math.round(27 + l * 42), bl = Math.round(56 + l * 60);
        facets.push(`<polygon points="${tri.map((p) => p.join(",")).join(" ")}" fill="rgb(${r},${g},${bl})" opacity="${f2(rr(rnd, 0.14, 0.3))}"/>`);
      }
    }
  }
  // ごく小さな静止ダスト（動かない微光）
  const dust = [];
  for (let i = 0; i < 70; i++) dust.push(`<circle cx="${f2(rr(rnd, 0, W))}" cy="${f2(rr(rnd, 0, H))}" r="${f2(rr(rnd, 0.3, 0.8))}" fill="#fff" opacity="${f2(rr(rnd, 0.12, 0.4))}"/>`);

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMid slice">
  <defs>
    <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#2c3560"/><stop offset="0.5" stop-color="#232945"/><stop offset="1" stop-color="#191d38"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.5" cy="0.06" r="0.75">
      <stop offset="0" stop-color="#4b5891" stop-opacity="0.5"/><stop offset="1" stop-color="#4b5891" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="${W}" height="${H}" fill="url(#sky)"/>
  <g>${facets.join("")}</g>
  <rect width="${W}" height="${H}" fill="url(#glow)"/>
  <g>${dust.join("")}</g>
</svg>
`;
  writeFileSync(resolve(ROOT, "project/assets/starfield.svg"), svg);
  console.log("✓ assets/starfield.svg（背景テクスチャ）");
}

// ============ 2) 瞬く星レイヤー（SMIL・小さめ） → js/starfield.js ============
{
  const rnd = mulberry32(70260706);
  const VW = 1200, VH = 800;
  const els = [];
  // ごく小さな星（半径 0.3〜1.0）を少数。非常にゆっくり瞬く。
  // アニメは軽量重視: 単純な opacity 3キーフレーム（spline補間なし）で描画負荷を抑える。
  for (let i = 0; i < 34; i++) {
    const x = f2(rr(rnd, 0, VW)), y = f2(rr(rnd, 0, VH));
    const r = f2(rr(rnd, 0.3, 1.0));
    const lo = f2(rr(rnd, 0.12, 0.28)), hi = f2(rr(rnd, 0.55, 0.9));
    const dur = f2(rr(rnd, 8, 15)), begin = f2(-rr(rnd, 0, 15));
    els.push(`<circle cx="${x}" cy="${y}" r="${r}" fill="#fff" opacity="${hi}"><animate attributeName="opacity" values="${hi};${lo};${hi}" dur="${dur}s" begin="${begin}s" repeatCount="indefinite"/></circle>`);
  }
  // 小さな4点キラメキを数点だけ
  for (let i = 0; i < 4; i++) {
    const x = f2(rr(rnd, 40, VW - 40)), y = f2(rr(rnd, 40, VH - 40)), s = f2(rr(rnd, 3, 5));
    const dur = f2(rr(rnd, 9, 16)), begin = f2(-rr(rnd, 0, 16));
    const path = `M0,${-s} C${s * 0.14},${-s * 0.14} ${s * 0.14},${-s * 0.14} ${s},0 C${s * 0.14},${s * 0.14} ${s * 0.14},${s * 0.14} 0,${s} C${-s * 0.14},${s * 0.14} ${-s * 0.14},${s * 0.14} ${-s},0 C${-s * 0.14},${-s * 0.14} ${-s * 0.14},${-s * 0.14} 0,${-s} Z`;
    els.push(`<path transform="translate(${x} ${y})" d="${path}" fill="#fff" opacity="0.8"><animate attributeName="opacity" values="0.8;0.22;0.8" dur="${dur}s" begin="${begin}s" repeatCount="indefinite"/></path>`);
  }
  const svgMarkup = `<svg class="star-layer" viewBox="0 0 ${VW} ${VH}" preserveAspectRatio="xMidYMid slice" aria-hidden="true" focusable="false">${els.join("")}</svg>`;
  const js = `// AUTO-GENERATED by scripts/gen-starfield.mjs — 手で編集しない。
// 濃色セクションに、非常にゆっくり瞬く星のインラインSVG（SMIL）を重ねる。
(function () {
  var SVG = ${JSON.stringify(svgMarkup)};
  var sels = ".basics, .entries, .cta, footer";
  function inject() {
    document.querySelectorAll(sels).forEach(function (sec) {
      if (sec.querySelector(":scope > .star-layer")) return;
      sec.insertAdjacentHTML("afterbegin", SVG);
    });
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", inject);
  else inject();
})();
`;
  writeFileSync(resolve(ROOT, "project/js/starfield.js"), js);
  console.log("✓ js/starfield.js（瞬く星レイヤー・SMIL）");
}
